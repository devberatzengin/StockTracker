using System.Linq.Expressions;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using StockTracker.Application.Common.Interfaces;
using StockTracker.Domain.Assignments;
using StockTracker.Domain.Catalog;
using StockTracker.Domain.Inventory;
using StockTracker.Domain.Locations;
using StockTracker.Domain.Common;
using StockTracker.Infrastructure.Identity;

namespace StockTracker.Infrastructure.Persistence;

public class AppDbContext(DbContextOptions options)
    : IdentityDbContext<AppUser, IdentityRole<Guid>, Guid>(options), IAppDbContext
{
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();

    public DbSet<Category> Categories => Set<Category>();

    public DbSet<Product> Products => Set<Product>();

    public DbSet<ProductBarcode> ProductBarcodes => Set<ProductBarcode>();

    public DbSet<Location> Locations => Set<Location>();

    public DbSet<Item> Items => Set<Item>();

    public DbSet<StockBalance> StockBalances => Set<StockBalance>();

    public DbSet<StockMovement> StockMovements => Set<StockMovement>();

    public DbSet<Assignment> Assignments => Set<Assignment>();

    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);

        builder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        ConfigureClientGeneratedKeys(builder);
        ApplySoftDeleteFilters(builder);
    }

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder.Properties<decimal>().HavePrecision(18, 3);
    }

    /// <summary>
    /// BaseEntity ids are generated in the domain (Guid v7). Marking them as never generated by the store
    /// lets EF treat a new child added to a tracked aggregate (e.g. a barcode) as Added, not Modified.
    /// </summary>
    private static void ConfigureClientGeneratedKeys(ModelBuilder builder)
    {
        var entityTypes = builder.Model.GetEntityTypes()
            .Where(t => t.BaseType is null && typeof(BaseEntity).IsAssignableFrom(t.ClrType));

        foreach (var entityType in entityTypes)
        {
            builder.Entity(entityType.ClrType).Property(nameof(BaseEntity.Id)).ValueGeneratedNever();
        }
    }

    private static void ApplySoftDeleteFilters(ModelBuilder builder)
    {
        var softDeletableRoots = builder.Model.GetEntityTypes()
            .Where(t => t.BaseType is null && typeof(ISoftDeletable).IsAssignableFrom(t.ClrType));

        foreach (var entityType in softDeletableRoots)
        {
            var parameter = Expression.Parameter(entityType.ClrType, "e");
            var filter = Expression.Lambda(
                Expression.Property(parameter, nameof(ISoftDeletable.IsActive)),
                parameter);

            builder.Entity(entityType.ClrType).HasQueryFilter(filter);
        }
    }
}
