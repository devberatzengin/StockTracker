#!/usr/bin/env python3
"""Generates docs/api.md from the API's Swagger document and the endpoint access table.

Usage (API running in Development):
    curl -s http://localhost:5180/swagger/v1/swagger.json -o /tmp/swagger.json
    python3 scripts/docs/gen_api_md.py /tmp/swagger.json > docs/api.md

Access levels come from EndpointAccessTests (the test that pins every endpoint's policy), so
the table cannot drift from what the tests enforce.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ACCESS_TABLE = ROOT / "backend/tests/StockTracker.Api.IntegrationTests/Security/EndpointAccessTests.cs"
EXAMPLES = Path(__file__).with_name("api_examples.md")
METHODS = ["get", "post", "put", "patch", "delete"]


def access_levels():
    levels = {}
    for method, route, access in re.findall(r'\{\s*"(\w+)",\s*"([^"]+)",\s*([\w.]+)\s*\}', ACCESS_TABLE.read_text()):
        # Route templates carry constraints ({id:guid}, {**key}); Swagger paths do not.
        path = "/" + re.sub(r"\{\**(\w+)(:[^}]*)?\}", r"{\1}", route)
        levels[(method.lower(), path)] = access.replace("Permissions.", "")
    return levels


def schema_name(content):
    for media in ("application/json", "multipart/form-data", "application/pdf",
                  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"):
        if media in (content or {}):
            schema = content[media].get("schema", {})
            ref = schema.get("$ref") or schema.get("items", {}).get("$ref")
            if ref:
                name = ref.rsplit("/", 1)[1]
                return f"`{name}[]`" if "items" in schema else f"`{name}`"
            if media != "application/json":
                return media.split("/")[1].replace("vnd.openxmlformats-officedocument.spreadsheetml.sheet", "xlsx")
            return f"`{schema.get('type', 'object')}`"
    return ""


def main():
    swagger = json.loads(Path(sys.argv[1]).read_text())
    levels = access_levels()
    by_tag = {}
    for path, operations in swagger["paths"].items():
        for method in METHODS:
            if method in operations:
                op = operations[method]
                by_tag.setdefault(op.get("tags", ["Other"])[0], []).append((path, method, op))

    out = [
        "# API",
        "",
        "Generated by `scripts/docs/gen_api_md.py` from the Swagger document (Development only:",
        "`/swagger`). All paths are under the same origin as the SPA; nginx proxies `/api`.",
        "",
        "- Auth: `Authorization: Bearer <accessToken>` from `POST /api/auth/login`; the refresh token",
        "  is an HttpOnly cookie used by `POST /api/auth/refresh` (ADR 005).",
        "- Access: `Anonymous`, `AnyUser` (any signed-in user) or a policy name. Policies map to roles",
        "  in `Permissions` (Admin, WarehouseManager, Staff).",
        "- Lists take `page`, `pageSize` (≤ 100), `search`, `sort` and return",
        "  `{ items, totalCount, page, pageSize }`.",
        "- Stock-changing commands (movements, reversal, assign/return, repair, count approval) accept an",
        "  `Idempotency-Key` header: the same key and body run once per user and return the first response;",
        "  the same key with another body is 422 `Idempotency.KeyReused`. Keys are kept 7 days.",
        "- Errors are ProblemDetails with Turkish `title`/`detail`: 400 validation (`errors`), 401, 403,",
        "  404, 409 concurrency, 422 domain rule (`code`), 429 login rate limit.",
        "",
    ]
    intro = len(out)
    total = 0
    for tag in sorted(by_tag):
        out += [f"## {tag}", "", "| Method | Path | Access | Body | Response |", "|---|---|---|---|---|"]
        for path, method, op in sorted(by_tag[tag], key=lambda o: (o[0], METHODS.index(o[1]))):
            body = schema_name(op.get("requestBody", {}).get("content"))
            ok = next((r for code, r in op.get("responses", {}).items() if code.startswith("2")), {})
            access = levels.get((method, path), "?")
            out.append(f"| {method.upper()} | `{path}` | {access} | {body} | {schema_name(ok.get('content'))} |")
            total += 1
        out.append("")
    out[intro:intro] = [f"{total} endpoints.", ""]
    if EXAMPLES.exists():
        out += [EXAMPLES.read_text().rstrip()]
    print("\n".join(out))


if __name__ == "__main__":
    main()
